#!/usr/bin/env python3
"""Compile and exercise the production HDMI EDID decoder under sanitizers."""
import os
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
source = r'''
#include "edid_timing.h"
#include <assert.h>

static void checksum(uint8_t* block) {
    block[127] = 0;
    for (unsigned i = 0; i < 127; i++) block[127] -= block[i];
}

int main() {
    uint8_t edid[256] = {0, 255, 255, 255, 255, 255, 255, 0};
    // 1920x1080p60 DTD read from both physical lab monitors.
    const uint8_t dtd[18] = {0x02,0x3a,0x80,0x18,0x71,0x38,0x2d,0x40,
        0x58,0x2c,0x45,0x00,0x0f,0x28,0x21,0,0,0x1e};
    memcpy(edid + 54, dtd, 18);
    checksum(edid);
    firmware_timing t;
    assert(preferred_edid_timing(edid, 128, t));
    assert(t.clock == 148500 && t.hdisplay == 1920 && t.vdisplay == 1080);
    assert(t.hsync_start == 2008 && t.hsync_end == 2052 && t.htotal == 2200);
    assert(t.vsync_start == 1084 && t.vsync_end == 1089 && t.vtotal == 1125);
    assert(t.vrefresh == 60 && t.flags == 515); // positive sync + DVI
    assert(!preferred_edid_timing(edid, 127, t));
    edid[20] ^= 1;
    assert(!preferred_edid_timing(edid, 128, t));
    edid[20] ^= 1;
    edid[126] = 1;
    checksum(edid);
    uint8_t* cea = edid + 128;
    cea[0] = 2; cea[1] = 3; cea[2] = 8;
    cea[4] = 0x63; cea[5] = 3; cea[6] = 12; cea[7] = 0;
    checksum(cea);
    assert(preferred_edid_timing(edid, 256, t) && t.flags == 3);
    // An interlaced preferred DTD is rejected; a supported CTA DTD is used.
    edid[71] |= 128; checksum(edid);
    assert(!preferred_edid_timing(edid, 128, t));
    memcpy(cea + 8, dtd, 18); checksum(cea);
    assert(preferred_edid_timing(edid, 256, t) && t.hdisplay == 1920);
    memset(cea + 8, 0, 18); checksum(cea);
    edid[35] = 0x20; checksum(edid);
    assert(preferred_edid_timing(edid, 256, t) && t.hdisplay == 640);
    // Dell P2415Q over HDMI (read on the lab Pi 2026-10-31): its preferred
    // timing is 3840x2160 at 60 Hz (594 MHz), beyond the firmware's default
    // limit; the same size at 30 Hz must win over 2560x1440 and 1080p.
    {
        static const uint8_t p2415q[256] = {0x00,0xff,0xff,0xff,0xff,0xff,0xff,0x00,0x10,0xac,0xc5,0xa0,0x4c,0x31,0x48,0x30,0x30,0x1a,0x01,0x03,0x80,0x35,0x1e,0x78,0xea,0xe2,0x45,0xa8,0x55,0x4d,0xa3,0x26,0x0b,0x50,0x54,0xa5,0x4b,0x00,0x71,0x4f,0x81,0x80,0xa9,0xc0,0xa9,0x40,0xd1,0xc0,0xe1,0x00,0x01,0x01,0x01,0x01,0x08,0xe8,0x00,0x30,0xf2,0x70,0x5a,0x80,0xb0,0x58,0x8a,0x00,0x0f,0x28,0x21,0x00,0x00,0x1a,0x00,0x00,0x00,0xff,0x00,0x38,0x36,0x36,0x48,0x36,0x36,0x42,0x51,0x30,0x48,0x31,0x4c,0x0a,0x00,0x00,0x00,0xfc,0x00,0x44,0x45,0x4c,0x4c,0x20,0x50,0x32,0x34,0x31,0x35,0x51,0x0a,0x20,0x00,0x00,0x00,0xfd,0x00,0x1d,0x4c,0x1e,0x8c,0x3c,0x00,0x0a,0x20,0x20,0x20,0x20,0x20,0x20,0x01,0xd7,0x02,0x03,0x40,0xf1,0x58,0x10,0x05,0x04,0x02,0x07,0x16,0x01,0x14,0x1f,0x12,0x13,0x27,0x20,0x21,0x22,0x03,0x06,0x11,0x15,0x5d,0x5e,0x5f,0x61,0x60,0x23,0x09,0x1f,0x07,0x83,0x01,0x00,0x00,0x6d,0x03,0x0c,0x00,0x20,0x00,0x00,0x78,0x20,0x00,0x60,0x03,0x02,0x01,0x67,0xd8,0x5d,0xc4,0x01,0x78,0xc0,0x07,0xe4,0x0f,0x00,0x00,0xc0,0x01,0x1d,0x80,0x18,0x71,0x1c,0x16,0x20,0x58,0x2c,0x25,0x00,0x0f,0x28,0x21,0x00,0x00,0x9e,0x04,0x74,0x00,0x30,0xf2,0x70,0x5a,0x80,0xb0,0x58,0x8a,0x00,0x0f,0x28,0x21,0x00,0x00,0x1e,0x56,0x5e,0x00,0xa0,0xa0,0xa0,0x29,0x50,0x30,0x20,0x35,0x00,0x0f,0x28,0x21,0x00,0x00,0x1a,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x82};
        assert(preferred_edid_timing(p2415q, 256, t));
        assert(t.hdisplay == 3840 && t.vdisplay == 2160 && t.vrefresh == 30);
        assert(t.clock == 297000 && (t.flags & (1u << 9)) == 0);
        assert(preferred_edid_timing(p2415q, 256, t, 600000));
        assert(t.hdisplay == 3840 && t.vdisplay == 2160 && t.vrefresh == 60);
        // Below 4K's clock the largest the Pi can send is 2560x1440.
        assert(preferred_edid_timing(p2415q, 256, t, 250000));
        assert(t.hdisplay == 2560 && t.vdisplay == 1440);
        // Its base block alone has no other detailed timing: VGA.
        assert(preferred_edid_timing(p2415q, 128, t, 250000));
        assert(t.hdisplay == 640);
    }
    // Malformed descriptors and CTA offsets must never read outside EDID.
    uint32_t random = 7;
    for (unsigned n = 0; n < 100000; n++) {
        for (unsigned i = 8; i < sizeof(edid); i++) {
            random = random * 1664525u + 1013904223u;
            edid[i] = random >> 24;
        }
        checksum(edid); checksum(cea);
        if (preferred_edid_timing(edid, 256, t)) {
            assert(t.hdisplay >= 320 && t.hdisplay <= 4096);
            assert(t.vdisplay >= 200 && t.vdisplay <= 2160);
            assert(t.hdisplay < t.hsync_start && t.hsync_start < t.hsync_end);
            assert(t.hsync_end <= t.htotal && t.vsync_end <= t.vtotal);
        }
    }
}
'''
with tempfile.TemporaryDirectory(prefix="rpi-edid-", dir=os.environ.get(
        "TMPDIR", "/mnt/HaikuWork/tmp")) as work:
    path = Path(work)
    (path / "test.cpp").write_text(source)
    subprocess.run([os.environ.get("CXX", "c++"), "-std=c++11", "-g",
                    "-fsanitize=address,undefined", "-fno-omit-frame-pointer",
                    "-I" + str(root / "src/add-ons/kernel/drivers/graphics/rpi_display"),
                    str(path / "test.cpp"), "-o", str(path / "test")], check=True)
    subprocess.run([str(path / "test")], check=True)
print("HDMI EDID timing tests passed (including 100,000 malformed EDIDs)")
