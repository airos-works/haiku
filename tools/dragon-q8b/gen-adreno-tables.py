#!/usr/bin/env python3
"""Generate src/add-ons/kernel/drivers/graphics/adreno/a690_tables.h from a
Linux tree: the A6XX register offsets the driver uses (from
drivers/gpu/drm/msm/registers/adreno/a6xx.xml) and the A690's hardware clock
gating and CP protection tables (from adreno/a6xx_catalog.c).

    gen-adreno-tables.py <linux tree> <output>
"""
import re
import sys
import xml.etree.ElementTree as ET

linux, output = sys.argv[1], sys.argv[2]
msm = f"{linux}/drivers/gpu/drm/msm"


def strip_namespace(tree):
    for element in tree.iter():
        if "}" in element.tag:
            element.tag = element.tag.split("}", 1)[1]


def a6xx_variant(variants):
    """True if a "variants" attribute includes the A6XX generation."""
    if not variants:
        return True
    for part in variants.split(","):
        part = part.strip()
        if part in ("A6XX", "A6XX-") or part.startswith("A6XX"):
            return True
        if part.endswith("-") and part[:-1] < "A6XX":
            return True
    return False


registers = {}
arrays = {}
tree = ET.parse(f"{msm}/registers/adreno/a6xx.xml")
strip_namespace(tree)
for domain in tree.getroot().iter("domain"):
    if domain.get("name") != "A6XX":
        continue
    for element in domain:
        if element.tag in ("reg32", "reg64"):
            if a6xx_variant(element.get("variants")):
                registers.setdefault(element.get("name"),
                                     int(element.get("offset"), 16))
        elif element.tag == "array":
            if a6xx_variant(element.get("variants")):
                arrays.setdefault(element.get("name"),
                                  (int(element.get("offset"), 16),
                                   int(element.get("stride"), 16 if element.get("stride", "").startswith("0x") else 10)))

catalog = open(f"{msm}/adreno/a6xx_catalog.c").read()


def table(name):
    match = re.search(r"static const struct adreno_reglist %s\[\] = \{(.*?)\n\};" % name,
                      catalog, re.S)
    entries = []
    for reg, value in re.findall(r"\{\s*REG_A6XX_(\w+),\s*(0x[0-9A-Fa-f]+)\s*\}", match.group(1)):
        entries.append((registers[reg], int(value, 16), reg))
    return entries


def protect(name):
    match = re.search(r"static const u32 %s\[\] = \{(.*?)\n\};" % name, catalog, re.S)
    entries = []
    for kind, start, count in re.findall(r"A6XX_PROTECT_(RDONLY|NORDWR)\((0x[0-9a-f]+),\s*(0x[0-9a-f]+)\)",
                                         match.group(1)):
        value = (int(count, 16) << 18) | int(start, 16)
        if kind == "NORDWR":
            value |= 1 << 31
        entries.append(value)
    count = int(re.search(r"DECLARE_ADRENO_PROTECT\(%s,\s*(\d+)\)" % name.replace("_regs", ""),
                          catalog).group(1))
    return entries, count


used = sorted(set(sys.argv[3:]) if len(sys.argv) > 3 else set())
lines = ["/* Generated by tools/dragon-q8b/gen-adreno-tables.py from Linux "
         f"{open(f'{linux}/Makefile').read().split('VERSION = ')[1].split()[0]}."
         f"{open(f'{linux}/Makefile').read().split('PATCHLEVEL = ')[1].split()[0]}"
         " (drm/msm a6xx.xml, a6xx_catalog.c). */",
         "#ifndef A690_TABLES_H", "#define A690_TABLES_H", ""]
needed = re.findall(r"\bREG_A6XX_(\w+)", open(sys.argv[2].replace("a690_tables.h", "adreno.cpp")).read()) \
    if len(sys.argv) <= 3 else used
for name in sorted(set(needed)):
    if name in registers:
        lines.append(f"#define REG_A6XX_{name:<40} 0x{registers[name]:05x}")
    elif name in arrays:
        offset, stride = arrays[name]
        lines.append(f"#define REG_A6XX_{name}(i){' ' * max(1, 37 - len(name))} (0x{offset:05x} + {stride} * (i))")
    else:
        sys.exit(f"unknown register {name}")
lines.append("")
lines.append("static const struct { uint32 offset; uint32 value; } kA690ClockGating[] = {")
for offset, value, name in table("a690_hwcg"):
    lines.append(f"\t{{ 0x{offset:05x}, 0x{value:08x} }},\t// {name}")
lines.append("};")
lines.append("")
entries, count = protect("a690_protect_regs")
lines.append(f"#define A690_PROTECT_COUNT\t{count}")
lines.append("static const uint32 kA690Protect[] = {")
for value in entries:
    lines.append(f"\t0x{value:08x},")
lines.append("};")
lines += ["", "#endif"]
open(output, "w").write("\n".join(lines) + "\n")
