#!/usr/bin/env python3
# Generates EmojiTables.cpp from the Unicode emoji data.
#
# usage: gen_emoji_tables.py <emoji-data.txt> > EmojiTables.cpp
#
# emoji-data.txt is https://www.unicode.org/Public/<version>/ucd/emoji/.
import re
import sys

path = sys.argv[1]
properties = {"Emoji_Presentation": [], "Extended_Pictographic": []}
version = "unknown"

with open(path, encoding="utf-8") as f:
	for line in f:
		m = re.match(r"# Used with Emoji Version (\S+)", line)
		if m:
			version = m.group(1)
		line = line.split("#", 1)[0].strip()
		if not line:
			continue
		fields = [x.strip() for x in line.split(";")]
		if fields[1] not in properties:
			continue
		span = fields[0].split("..")
		properties[fields[1]].append((int(span[0], 16), int(span[-1], 16)))


def merged(spans):
	result = []
	for first, last in sorted(spans):
		if result and first <= result[-1][1] + 1:
			result[-1] = (result[-1][0], max(last, result[-1][1]))
		else:
			result.append((first, last))
	return result


print("""/*
 * Copyright 2026, Haiku, Inc. All rights reserved.
 * Distributed under the terms of the MIT License.
 *
 * Generated by gen_emoji_tables.py from the Unicode %s emoji data.
 * Do not edit.
 */


#include "EmojiTables.h"
""" % version)

for name, table in (("Emoji_Presentation", "kEmojiPresentationRanges"),
		("Extended_Pictographic", "kExtendedPictographicRanges")):
	spans = merged(properties[name])
	print("\nconst emoji_range %s[] = {" % table)
	for first, last in spans:
		print("\t{ 0x%04x, 0x%04x }," % (first, last))
	print("};\nconst int32 %sCount = %d;" % (table[:-6] + "Range", len(spans)))
