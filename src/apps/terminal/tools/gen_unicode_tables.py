#!/usr/bin/env python3
# Generates emulator/UnicodeTables.cpp from the Unicode Character Database.
#
# usage: gen_unicode_tables.py <ucd dir> > emulator/UnicodeTables.cpp
#
# The directory needs EastAsianWidth.txt, DerivedGeneralCategory.txt,
# DerivedCoreProperties.txt, GraphemeBreakProperty.txt and emoji-data.txt of
# one Unicode version (https://www.unicode.org/Public/<version>/ucd/).
import os
import re
import sys

ucd = sys.argv[1]
MAX = 0x110000


def ranges(name):
	"""Yields (first, last, fields) for every data line of a UCD file."""
	with open(os.path.join(ucd, name), encoding="utf-8") as f:
		for line in f:
			line = line.split("#", 1)[0].strip()
			if not line:
				continue
			fields = [x.strip() for x in line.split(";")]
			span = fields[0].split("..")
			first = int(span[0], 16)
			last = int(span[-1], 16)
			yield first, last, fields[1:]


def version():
	with open(os.path.join(ucd, "EastAsianWidth.txt"), encoding="utf-8") as f:
		m = re.search(r"EastAsianWidth-(\d+\.\d+\.\d+)", f.readline())
		return m.group(1) if m else "unknown"


category = ["Cn"] * MAX
for a, b, f in ranges("DerivedGeneralCategory.txt"):
	for c in range(a, b + 1):
		category[c] = f[0]

eaw = ["N"] * MAX
for a, b, f in ranges("EastAsianWidth.txt"):
	for c in range(a, b + 1):
		eaw[c] = f[0]

emojiPresentation = [False] * MAX
extendedPictographic = [False] * MAX
for a, b, f in ranges("emoji-data.txt"):
	for c in range(a, b + 1):
		if f[0] == "Emoji_Presentation":
			emojiPresentation[c] = True
		elif f[0] == "Extended_Pictographic":
			extendedPictographic[c] = True

defaultIgnorable = [False] * MAX
incb = [None] * MAX
for a, b, f in ranges("DerivedCoreProperties.txt"):
	for c in range(a, b + 1):
		if f[0] == "Default_Ignorable_Code_Point":
			defaultIgnorable[c] = True
		elif f[0] == "InCB":
			incb[c] = f[1]

gcb = ["Other"] * MAX
for a, b, f in ranges("GraphemeBreakProperty.txt"):
	for c in range(a, b + 1):
		gcb[c] = f[0]


def width(c):
	cat = category[c]
	if c == 0:
		return 0
	if cat in ("Cc",):
		return 0 if c < 0xa0 else 1
	if cat in ("Mn", "Me"):
		return 0
	if cat == "Cf" or defaultIgnorable[c]:
		# U+00AD soft hyphen is shown; other format characters are not
		return 1 if c == 0x00ad else 0
	if 0x1160 <= c <= 0x11ff or 0xd7b0 <= c <= 0xd7ff:
		# Hangul medial vowels and final consonants join the syllable
		return 0
	if cat in ("Cs",):
		return 1
	if eaw[c] in ("W", "F") or emojiPresentation[c]:
		return 2
	if 0x1f1e6 <= c <= 0x1f1ff:
		return 2
	return 1


GCB_VALUES = ["Other", "CR", "LF", "Control", "Extend", "ZWJ",
	"Regional_Indicator", "Prepend", "SpacingMark", "L", "V", "T", "LV",
	"LVT"]
INCB_VALUES = {None: 0, "Linker": 1, "Consonant": 2, "Extend": 3}

# One property byte per code point: bits 0-1 width (0, 1, 2),
# bits 2-5 grapheme cluster break, bit 6 Extended_Pictographic,
# bit 7 Emoji_Presentation; a second byte holds InCB.
props = []
for c in range(MAX):
	value = width(c) | (GCB_VALUES.index(gcb[c]) << 2)
	if extendedPictographic[c]:
		value |= 0x40
	if emojiPresentation[c]:
		value |= 0x80
	props.append(value | (INCB_VALUES[incb[c]] << 8))

# Two level table: 256 code point blocks, deduplicated.
BLOCK = 256
blocks = []
blockIndex = {}
stage1 = []
for start in range(0, MAX, BLOCK):
	block = tuple(props[start:start + BLOCK])
	if block not in blockIndex:
		blockIndex[block] = len(blocks)
		blocks.append(block)
	stage1.append(blockIndex[block])

out = sys.stdout
out.write("""/*
 * Copyright 2026, Haiku, Inc. All rights reserved.
 * Distributed under the terms of the MIT License.
 *
 * Generated by tools/gen_unicode_tables.py from the Unicode %s
 * Character Database. Do not edit.
 */


#include "UnicodeTables.h"


const char* const kUnicodeVersion = "%s";

const uint16 kUnicodeStage1[%d] = {
""" % (version(), version(), len(stage1)))
for i in range(0, len(stage1), 16):
	out.write("\t" + ", ".join(str(x) for x in stage1[i:i + 16]) + ",\n")
out.write("};\n\nconst uint16 kUnicodeStage2[%d][%d] = {\n" % (len(blocks), BLOCK))
for block in blocks:
	out.write("\t{\n")
	for i in range(0, BLOCK, 16):
		out.write("\t\t" + ", ".join("0x%x" % x for x in block[i:i + 16]) + ",\n")
	out.write("\t},\n")
out.write("};\n")
