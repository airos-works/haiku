#!/bin/sh
# Compiles the GLSL compute shaders in this directory to SPIR-V and writes
# them as C arrays to Shaders.inc.h, which is what the add-on is built
# from: the Haiku build needs no shader compiler. Run it after changing
# a shader and commit the result. Needs glslangValidator (glslang).
#
# A line "name source [-DDEFINE ...]" below is one shader module.

set -e
cd "$(dirname "$0")"

GLSLANG=${GLSLANG:-glslangValidator}
OUTPUT=Shaders.inc.h
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

SHADERS="
conv conv.comp
conv_pointwise conv.comp -DPOINTWISE
conv_quad conv.comp -DQUAD
depthwise depthwise.comp
depthwise_multiplier depthwise.comp -DMULTIPLIER
depthwise_grid depthwise.comp -DGRID
pool_average pool.comp
pool_maximum pool.comp -DMAXIMUM
binary binary.comp
unary unary.comp
softmax softmax.comp
mean mean.comp
pad pad.comp
resize resize.comp
concat concat.comp
repack repack.comp
"

{
	echo "/*"
	echo " * Copyright 2026, air/OS contributors."
	echo " * Distributed under the terms of the MIT License."
	echo " */"
	echo
	echo "// Generated by shaders/compile.sh from the .comp files beside it"
	echo "// ($($GLSLANG --version | head -1))."
	echo "// Do not edit."
	echo
} > "$WORK/out.h"

echo "$SHADERS" | while read -r name source defines; do
	[ -n "$name" ] || continue
	# shellcheck disable=SC2086
	$GLSLANG -V --target-env vulkan1.0 -S comp -I. $defines \
		-o "$WORK/$name.spv" "$source" > "$WORK/log" 2>&1 \
		|| { cat "$WORK/log" >&2; exit 1; }
	{
		echo "static const uint32 kShader_$name[] = {"
		od -An -v -tx4 -w24 "$WORK/$name.spv" \
			| sed -e 's/^ */\t0x/' -e 's/ \+/, 0x/g' -e 's/$/,/'
		echo "};"
		echo
	} >> "$WORK/out.h"
done

mv "$WORK/out.h" "$OUTPUT"
echo "wrote $OUTPUT"
