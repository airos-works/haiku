/*!	The resolv.conf the net_server writes from the interfaces' leases
	(airos-works/haiku#233): the servers of every interface in order, the
	lines it did not write kept, the markers of Network preferences honoured.
*/


#include <stdio.h>

#include "ResolvConf.h"


using namespace ResolvConf;


static int sFailures = 0;


static void
check(const char* what, bool changes, const std::string& result,
	bool expectedChanges, const std::string& expected)
{
	bool ok = changes == expectedChanges && (!changes || result == expected);
	printf("%s: %s\n", ok ? "ok  " : "FAIL", what);
	if (!ok) {
		printf("  got (%s):\n%s  expected (%s):\n%s", changes ? "write" : "keep",
			result.c_str(), expectedChanges ? "write" : "keep",
			expected.c_str());
		sFailures++;
	}
}


static Source
source(const char* first, const char* second, const char* domain)
{
	Source source;
	if (first != NULL)
		source.nameservers.push_back(first);
	if (second != NULL)
		source.nameservers.push_back(second);
	if (domain != NULL)
		source.domain = domain;
	return source;
}


int
main()
{
	std::vector<Source> sources;
	sources.push_back(source("192.168.1.1", NULL, "home.lan"));
	sources.push_back(source("10.0.3.3", "192.168.1.1", "phone.lan"));
	std::string block = MakeBlock(sources);
	std::string expectedBlock = "# Added automatically by DHCP\n"
		"nameserver 192.168.1.1\n"
		"nameserver 10.0.3.3\n"
		"domain home.lan\n"
		"# End of automatic DHCP additions\n";
	check("block: servers in order, each once, first domain", true, block,
		true, expectedBlock);

	std::string emptyBlock = MakeBlock(std::vector<Source>());
	check("block without sources", true, emptyBlock, true,
		"# Added automatically by DHCP\n"
		"# End of automatic DHCP additions\n");

	std::string result;
	bool changes = Merge("", false, block, result);
	check("no file", changes, result, true, block);

	std::string old = "# Added automatically by DHCP\n"
		"nameserver 10.0.3.3\n"
		"nameserver 10.0.3.4\n"
		"nameserver 10.0.3.5\n"
		"# End of automatic DHCP additions\n";
	changes = Merge(old, true, block, result);
	check("old block replaced, not overwritten in place", changes, result,
		true, block);

	std::string handWritten = "# my VPN\nnameserver 172.16.0.1\n" + old
		+ "options timeout:2\n";
	changes = Merge(handWritten, true, block, result);
	check("lines outside the block kept in place", changes, result, true,
		"# my VPN\nnameserver 172.16.0.1\n" + block + "options timeout:2\n");

	changes = Merge("nameserver 172.16.0.1", true, block, result);
	check("file without a block (no final newline) gets one at the end",
		changes, result, true, "nameserver 172.16.0.1\n" + block);

	std::string preferences = "# Static DNS entries\n"
		"# Generated by Network preferences\n"
		"nameserver\t9.9.9.9\n"
		"# Dynamic DNS entries\n"
		"# may be altered by DHCP\n"
		"nameserver 10.0.3.3\n"
		"nameserver 10.0.3.4\n";
	changes = Merge(preferences, true, block, result);
	check("Network preferences: kept above the dynamic marker, block below",
		changes, result, true,
		"# Static DNS entries\n"
		"# Generated by Network preferences\n"
		"nameserver\t9.9.9.9\n"
		"# Dynamic DNS entries\n" + block);

	changes = Merge("# Static DNS Only\nnameserver 1.1.1.1\n", true, block,
		result);
	check("static only: left alone", changes, result, false, "");

	changes = Merge(block, true, block, result);
	check("same block again: same contents", changes, result, true, block);

	printf("%s\n", sFailures == 0 ? "PASS" : "FAILED");
	return sFailures == 0 ? 0 : 1;
}
